pub struct BitField {
    bits: Vec<u64>,
    size: usize,
}

impl BitField {
    pub fn new(bits: Vec<u64>, size: usize) -> Self {
        if size > 64 * bits.len() {
            panic!(
                "BitField size cannot be greater than number of bits in bits (size: {size}, bits: {})",
                64 * bits.len()
            )
        }
        Self { bits, size }
    }

    pub fn iter(&self) -> impl Iterator<Item = bool> {
        self.bits
            .iter()
            .flat_map(|chunk| POSITIONS.iter().map(move |position| position & chunk > 0))
            .take(self.size)
    }
}

impl BitOrAssign for BitField {
    fn bitor_assign(&mut self, rhs: Self) {
        self.bits
            .iter_mut()
            .zip(rhs.bits.iter())
            .for_each(|(x, y)| *x |= y);
    }
}

impl BitAndAssign for BitField {
    fn bitand_assign(&mut self, rhs: Self) {
        self.bits
            .iter_mut()
            .zip(rhs.bits.iter())
            .for_each(|(x, y)| *x &= y);
    }
}

impl Not for BitField {
    type Output = Self;

    fn not(mut self) -> Self::Output {
        self.bits.iter_mut().for_each(|x| *x = !*x);
        self
    }
}

